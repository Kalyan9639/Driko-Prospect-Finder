import io
import csv
import json
from datetime import datetime, timezone
from app.schemas import ICPReport, ClaimStatus


def generate_markdown_report(report: ICPReport) -> str:
    """
    Exports the ICPReport into an epistemic-grade, human-readable Markdown document,
    complete with Grounded Proof URLs, Verbatim Evidence, and Decision-Maker Contacts.
    """
    now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    inc = report.geography.include if hasattr(report.geography, "include") else report.geography.get("include", [])
    exc = report.geography.exclude if hasattr(report.geography, "exclude") else report.geography.get("exclude", [])

    md: list[str] = [
        f"# Ideal Customer Profile (ICP) & Live B2B Prospect Discovery",
        f"*Generated by ICP Clarity Lab — {now_str}*",
        "",
        "---",
        "",
        "## 1. Executive Summary & Core Hypothesis",
        f"**Business Summary:** {report.business_summary}",
        f"**ICP Thesis:** {report.icp_statement}",
        f"**Offering:** {report.offering}",
        f"**Target Entity:** {report.target_entity}",
        f"**Geographic Scope:** Include: {', '.join(inc) or 'Global'} | Exclude: {', '.join(exc) or 'None'}",
        "",
        "---",
        "",
        "## 2. Epistemic Assumption Ledger",
        "> **Ledger Legend:**",
        "> - `[USER-PROVIDED]` : Explicitly stated by the founder.",
        "> - `[USER-CONFIRMED]` : Generated interpretation reviewed and approved by the founder.",
        "> - `[AI INTERPRETATION]` : Structured synthesis of founder statements.",
        "> - `[EXTERNAL SIGNAL]` : Grounded evidence from public APIs/URLs (not guaranteed demand).",
        "> - `[ASSUMPTION — UNVERIFIED]` : Plausible hypothesis requiring validation.",
        "> - `[UNKNOWN — GAPS]` : Critical missing requirement.",
        "",
        "| ID | Criterion / Statement | Category | Origin Status | Explanation & Sources |",
        "| :--- | :--- | :--- | :--- | :--- |"
    ]

    status_tag_map = {
        ClaimStatus.USER_PROVIDED: "**[USER-PROVIDED]**",
        ClaimStatus.USER_CONFIRMED: "**[USER-CONFIRMED]**",
        ClaimStatus.AI_INTERPRETATION: "*[AI INTERPRETATION]*",
        ClaimStatus.EXTERNAL_SIGNAL: "*[EXTERNAL SIGNAL]*",
        ClaimStatus.ASSUMPTION: "`[ASSUMPTION — UNVERIFIED]`",
        ClaimStatus.UNKNOWN: "`[UNKNOWN — GAPS]`",
    }

    for item in report.ledger_items:
        tag = status_tag_map.get(item.status, f"[{item.status.value}]")
        if item.user_confirmed and item.status != ClaimStatus.USER_PROVIDED:
            tag = "**[USER-CONFIRMED]**"

        source_str = f" [Source]({item.source_url})" if item.source_url else ""
        statement_clean = item.statement.replace("|", "/")
        explanation_clean = item.explanation.replace("|", "/")
        md.append(f"| `{item.id}` | {statement_clean} | {item.category} | {tag} | {explanation_clean}{source_str} |")

    if report.unknowns:
        md.extend([
            "",
            "### Critical Missing Information (Unknowns to Investigate)",
            *[f"- {u}" for u in report.unknowns]
        ])

    md.extend([
        "",
        "---",
        "",
        "## 3. Buyer Persona & Decision-Maker Matrix (Module 4)",
        "The ICP defines the *target company*; this matrix defines the *human purchasing committee*.",
        ""
    ])

    for p in report.buyer_personas:
        md.extend([
            f"### {p.role_title} (`{p.role_type.value.upper()}`)",
            f"- **Core Operational Pain & Stake:** {p.core_pain_and_stake}",
            f"- **Key Evaluation Criteria:** {', '.join(p.evaluation_criteria)}",
            f"- **Authority Qualification:** *{p.authority_qualification}*",
            f"- **Deal-Breaker / Objection Risk:** {p.deal_breaker_risk}",
            ""
        ])

    md.extend([
        "---",
        "",
        "## 4. Mom-Test Customer Validation Interview Guide (Module 5)",
        "Use these non-leading questions in discovery interviews. **Never pitch during discovery.**",
        ""
    ])

    for q in report.validation_questions:
        md.extend([
            f"#### Question `{q.id}` (Target: {q.target_persona_title} | Linked: `{q.linked_item_id}`)",
            f"> **Discovery Question:** \"{q.discovery_question}\"",
            f"- **Strong Validation Signal:** {q.validation_signal}",
            f"- **Invalidation / Warning Signal:** {q.invalidation_signal}",
            ""
        ])

    md.extend([
        "---",
        "",
        "## 5. Exploratory Customer Discovery Roadmap (Module 6)",
        ""
    ])

    for step in report.validation_plan:
        md.extend([
            f"**Step {step.step_number}: {step.action}**",
            f"- *Target Profile:* {step.target_profile}",
            f"- *Uncertainty Addressed:* {step.uncertainty_addressed}",
            f"- *Decision Rule:* **{step.decision_rule}**",
            ""
        ])

    if report.discovered_prospects:
        md.extend([
            "---",
            "",
            "## 6. Live Matched Target Companies, Decision-Makers & Verifiable Proof",
            "Real companies discovered across unblocked public sources actively experiencing this problem:",
            ""
        ])
        for idx, p in enumerate(report.discovered_prospects, 1):
            dm_lines = []
            for dm in p.decision_makers:
                li_str = f" ([Verified LinkedIn]({dm.linkedin_url}))" if dm.linkedin_url else f" ([Search LinkedIn]({dm.linkedin_search_url}))"
                email_str = f" — `{dm.email}` ({dm.email_verification_status})" if dm.email else " — *(No private email published on website)*"
                dm_lines.append(f"  - **{dm.full_name}** ({dm.role_title}){li_str}{email_str}\n    *Responsibility:* {dm.stakeholder_responsibility}")

            emails_str = ", ".join(p.public_emails) or "None publicly listed on website"
            phones_str = ", ".join(p.phone_numbers) or "None listed"

            proof_block = []
            if p.evidence_proof:
                proof_block = [
                    f"> **Verifiable Ground-Truth Proof:** [{p.evidence_proof.source_name}]({p.evidence_proof.proof_url})",
                    f"> *\"{p.evidence_proof.verbatim_excerpt}\"*",
                    f"> **Why this proves fit:** {p.evidence_proof.fit_explanation}",
                    ""
                ]

            md.extend([
                f"### {idx}. [{p.company_name}]({p.website_url}) — Fit Score: {p.fit_score}/100",
                f"- **Scale & Location:** `{p.company_size_tier}` | {p.location}",
                *proof_block,
                f"- **Verified Public Inboxes:** {emails_str}",
                f"- **Office Phone:** {phones_str}",
                f"- **Company LinkedIn:** {p.company_linkedin_url or 'N/A'}",
                f"- **Identified Decision-Makers:**",
                *(dm_lines if dm_lines else ["  - *No individual executive names publicly indexed on website*"]),
                ""
            ])
            if p.outreach_draft:
                md.extend([
                    "> **AI-Crafted Cold Email Subject:** " + p.outreach_draft.subject_line,
                    "> ```",
                    "> " + p.outreach_draft.cold_email_body.replace("\n", "\n> "),
                    "> ```",
                    "> **LinkedIn Connection Note:** *" + p.outreach_draft.linkedin_dm_note + "*",
                    "> **Mom-Test Discovery Opener:** *" + p.outreach_draft.mom_test_opener + "*",
                    ""
                ])

    if report.external_signals:
        md.extend([
            "---",
            "",
            "## 7. Grounded External Evidence Audit",
            "Discussions and public references used to enrich this profile:",
            ""
        ])
        for s in report.external_signals:
            md.append(f"- **[{s.source_type.upper()}]** [{s.title}]({s.url}) — *\"{s.snippet}\"*")

    md.extend([
        "",
        "---",
        "",
        "## 8. Audit Telemetry",
        f"- **Model Used:** `{report.telemetry.get('model_used', 'N/A')}`",
        f"- **Total Tokens Consumed:** `{report.telemetry.get('total_tokens', 0)}` (Prompt: {report.telemetry.get('prompt_tokens', 0)} / Completion: {report.telemetry.get('completion_tokens', 0)})",
        f"- **Cache Hit:** `{report.telemetry.get('cache_hit', False)}`",
        f"- **Elapsed Time:** `{report.telemetry.get('elapsed_seconds', 0.0)}s`",
        "",
        "> *Principle: An ICP generated by AI represents a structured hypothesis, not verified customer demand. Genuine validation occurs only through actual customer discovery.*"
    ])

    return "\n".join(md)


def generate_json_report(report: ICPReport) -> str:
    """Exports the ICPReport into formatted JSON."""
    return report.model_dump_json(indent=2)


def generate_prospects_csv(report: ICPReport) -> str:
    """
    Exports discovered target companies, decision-makers, verified emails,
    proof URLs, and outreach copy into a CRM-ready CSV.
    """
    output = io.StringIO()
    writer = csv.writer(output, quoting=csv.QUOTE_MINIMAL)

    writer.writerow([
        "Company Name",
        "Official Website",
        "Company Size Tier",
        "Location",
        "Fit Score",
        "Observable Problem Evidence",
        "Proof Verification URL",
        "Proof Quoted Excerpt",
        "Public Inboxes (Verified on Site)",
        "Office Phone Numbers",
        "Company LinkedIn",
        "Decision Maker 1 Name",
        "Decision Maker 1 Title",
        "Decision Maker 1 Responsibility",
        "Decision Maker 1 LinkedIn Profile",
        "Decision Maker 1 Search URL",
        "Decision Maker 2 Name",
        "Decision Maker 2 Title",
        "Decision Maker 2 Responsibility",
        "AI Cold Email Subject",
        "AI Cold Email Body",
        "AI LinkedIn Note",
        "Mom Test Discovery Opener",
        "CRM Status"
    ])

    for p in report.discovered_prospects:
        dm1 = p.decision_makers[0] if len(p.decision_makers) > 0 else None
        dm2 = p.decision_makers[1] if len(p.decision_makers) > 1 else None

        proof_url = p.evidence_proof.proof_url if p.evidence_proof else p.source_url
        proof_excerpt = p.evidence_proof.verbatim_excerpt if p.evidence_proof else p.problem_symptom_matched

        writer.writerow([
            p.company_name,
            p.website_url,
            p.company_size_tier,
            p.location,
            p.fit_score,
            p.problem_symptom_matched,
            proof_url,
            proof_excerpt,
            "; ".join(p.public_emails),
            "; ".join(p.phone_numbers),
            p.company_linkedin_url or "",
            dm1.full_name if dm1 else "",
            dm1.role_title if dm1 else "",
            dm1.stakeholder_responsibility if dm1 else "",
            dm1.linkedin_url or "" if dm1 else "",
            dm1.linkedin_search_url if dm1 else "",
            dm2.full_name if dm2 else "",
            dm2.role_title if dm2 else "",
            dm2.stakeholder_responsibility if dm2 else "",
            p.outreach_draft.subject_line if p.outreach_draft else "",
            p.outreach_draft.cold_email_body if p.outreach_draft else "",
            p.outreach_draft.linkedin_dm_note if p.outreach_draft else "",
            p.outreach_draft.mom_test_opener if p.outreach_draft else "",
            p.crm_status
        ])

    return output.getvalue()
